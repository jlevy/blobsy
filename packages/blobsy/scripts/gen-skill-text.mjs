#!/usr/bin/env node
/**
 * Generate src/skill-text.ts from SKILL.md (single source of truth).
 *
 * Three divergent skill texts existed — SKILL.md, a hand-maintained
 * skill-text.ts, and shipped docs — and the one agents actually received
 * omitted the recommended `add` workflow (review finding DOCS-01).
 * Edit SKILL.md; never edit skill-text.ts by hand.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(__dirname, '..');

const skillMd = readFileSync(join(pkgRoot, 'SKILL.md'), 'utf-8');

const generated = `/**
 * GENERATED FILE — do not edit. Source of truth: packages/blobsy/SKILL.md.
 * Regenerated by scripts/gen-skill-text.mjs during \`pnpm build\`.
 *
 * This is what \`blobsy skill\` prints and what \`blobsy setup --auto\`
 * installs into .claude/skills/blobsy/SKILL.md.
 */

export const SKILL_TEXT: string = ${JSON.stringify(skillMd)};
`;

writeFileSync(join(pkgRoot, 'src', 'skill-text.ts'), generated);
